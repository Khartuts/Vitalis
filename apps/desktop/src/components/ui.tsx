import * as Dialog from "@radix-ui/react-dialog";
import * as SwitchP from "@radix-ui/react-switch";
import * as TabsP from "@radix-ui/react-tabs";
import * as Tooltip from "@radix-ui/react-tooltip";
import { AlertTriangle, Info, Loader2, X } from "lucide-react";
import type { ReactNode } from "react";

export function cx(...c: (string | false | null | undefined)[]) {
  return c.filter(Boolean).join(" ");
}

export function Card({ title, subtitle, actions, children, className, onClick, testId }: {
  title?: ReactNode; subtitle?: ReactNode; actions?: ReactNode; children: ReactNode; className?: string;
  onClick?: () => void; testId?: string;
}) {
  const interactive = !!onClick;
  return (
    <section data-testid={testId}
      className={cx("rounded-xl border border-line bg-s1 p-4 fade-in", interactive && "cursor-pointer hover:border-line-strong transition-colors", className)}
      onClick={onClick} onKeyDown={interactive ? (e) => { if (e.key === "Enter") onClick?.(); } : undefined}
      tabIndex={interactive ? 0 : undefined} role={interactive ? "button" : undefined}>
      {(title || actions) && (
        <header className="mb-3 flex items-start justify-between gap-3">
          <div className="min-w-0">
            {title && <h3 className="text-[13px] font-semibold tracking-wide text-fg">{title}</h3>}
            {subtitle && <p className="mt-0.5 text-xs text-muted">{subtitle}</p>}
          </div>
          {actions && <div className="flex shrink-0 items-center gap-1" onClick={(e) => e.stopPropagation()}>{actions}</div>}
        </header>
      )}
      {children}
    </section>
  );
}

export function Button({ children, onClick, variant = "secondary", disabled, type = "button", title, size = "md", testId }: {
  children: ReactNode; onClick?: () => void; variant?: "primary" | "secondary" | "ghost" | "danger"; disabled?: boolean;
  type?: "button" | "submit"; title?: string; size?: "sm" | "md"; testId?: string;
}) {
  const v = {
    primary: "bg-accent text-white hover:brightness-110 border-transparent",
    secondary: "bg-s2 text-fg border-line hover:bg-s3",
    ghost: "bg-transparent text-fg2 border-transparent hover:bg-s2 hover:text-fg",
    danger: "bg-critical/90 text-white border-transparent hover:bg-critical",
  }[variant];
  return (
    <button type={type} onClick={onClick} disabled={disabled} title={title} data-testid={testId}
      className={cx("inline-flex items-center gap-1.5 rounded-lg border font-medium transition disabled:opacity-50 disabled:cursor-not-allowed",
        size === "sm" ? "px-2 py-1 text-xs" : "px-3 py-1.5 text-[13px]", v)}>
      {children}
    </button>
  );
}

export function Stat({ label, value, sub, tone, testId }: { label: ReactNode; value: ReactNode; sub?: ReactNode;
  tone?: "good" | "warning" | "critical" | "muted"; testId?: string }) {
  return (
    <div data-testid={testId}>
      <div className="text-xs text-muted">{label}</div>
      <div className={cx("num mt-0.5 text-2xl font-semibold tracking-tight", tone === "muted" ? "text-muted" : "text-fg")}>{value}</div>
      {sub && <div className="mt-0.5 text-xs text-fg2">{sub}</div>}
    </div>
  );
}

const PROV: Record<string, { label: string; cls: string; tip: string }> = {
  measured: { label: "Measured", cls: "border-line text-fg2", tip: "Sensor measurement reported by your device/app." },
  imported: { label: "Imported", cls: "border-line text-fg2", tip: "Value computed by the source (e.g. Samsung), imported verbatim." },
  calculated: { label: "Calculated", cls: "border-line text-fg2", tip: "Deterministic VITALIS calculation from your stored data." },
  estimated: { label: "Estimated", cls: "border-line text-warning", tip: "VITALIS model output with stated uncertainty." },
  user_entered: { label: "You entered", cls: "border-line text-fg2", tip: "Entered by you in the journal or manually." },
  ai_interpreted: { label: "AI interpretation", cls: "border-line text-fg2", tip: "Interpretation by the AI analyst of computed results." },
  synthetic: { label: "Synthetic", cls: "border-warning/40 text-warning", tip: "Demo data generated by VITALIS — not real." },
};

export function Prov({ kind }: { kind?: string | null }) {
  const p = PROV[kind ?? "calculated"] ?? PROV.calculated;
  return (
    <Tip text={p.tip}><span className={cx("rounded border px-1.5 py-px text-[10px] uppercase tracking-wider", p.cls)}>{p.label}</span></Tip>
  );
}

export function Badge({ children, tone = "neutral" }: { children: ReactNode; tone?: "neutral" | "good" | "warning" | "critical" | "accent" }) {
  const t = { neutral: "bg-s3 text-fg2", good: "bg-good/15 text-good", warning: "bg-warning/15 text-warning",
    critical: "bg-critical/15 text-critical", accent: "bg-accent/15 text-accent-ink" }[tone];
  return <span className={cx("inline-flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[11px] font-medium", t)}>{children}</span>;
}

export function Tip({ text, children }: { text: ReactNode; children: ReactNode }) {
  return (
    <Tooltip.Root delayDuration={250}>
      <Tooltip.Trigger asChild>{children}</Tooltip.Trigger>
      <Tooltip.Portal>
        <Tooltip.Content sideOffset={6} className="z-50 max-w-xs rounded-lg border border-line bg-s3 px-2.5 py-1.5 text-xs text-fg shadow-xl">
          {text}
        </Tooltip.Content>
      </Tooltip.Portal>
    </Tooltip.Root>
  );
}

export function InfoTip({ text }: { text: ReactNode }) {
  return (
    <Tip text={text}>
      <button type="button" aria-label="More information" className="inline-flex text-muted hover:text-fg"><Info size={13} /></button>
    </Tip>
  );
}

export function Skeleton({ h = 120 }: { h?: number }) {
  return <div className="skeleton w-full" style={{ height: h }} aria-busy="true" aria-label="Loading" />;
}

export function Empty({ title, children, icon }: { title: string; children?: ReactNode; icon?: ReactNode }) {
  return (
    <div className="flex flex-col items-center justify-center gap-2 rounded-lg border border-dashed border-line px-6 py-8 text-center">
      {icon ?? <Info size={20} className="text-muted" />}
      <div className="text-sm font-medium text-fg">{title}</div>
      {children && <div className="max-w-md text-xs text-fg2">{children}</div>}
    </div>
  );
}

export function ErrorBox({ error }: { error: unknown }) {
  const msg = error instanceof Error ? error.message : String(error);
  return (
    <div role="alert" className="flex items-start gap-2 rounded-lg border border-critical/40 bg-critical/10 px-3 py-2 text-xs text-fg">
      <AlertTriangle size={14} className="mt-0.5 shrink-0 text-critical" /> <span>{msg}</span>
    </div>
  );
}

export function Spinner({ label }: { label?: string }) {
  return <span className="inline-flex items-center gap-2 text-xs text-fg2"><Loader2 size={14} className="animate-spin" />{label}</span>;
}

export function Tabs({ tabs, value, onChange, children }: { tabs: { id: string; label: string }[]; value: string;
  onChange: (v: string) => void; children: ReactNode }) {
  return (
    <TabsP.Root value={value} onValueChange={onChange}>
      <TabsP.List className="mb-4 flex gap-1 border-b border-line" aria-label="Sections">
        {tabs.map((t) => (
          <TabsP.Trigger key={t.id} value={t.id}
            className="-mb-px border-b-2 border-transparent px-3 py-2 text-[13px] text-fg2 hover:text-fg data-[state=active]:border-accent data-[state=active]:text-fg">
            {t.label}
          </TabsP.Trigger>
        ))}
      </TabsP.List>
      {children}
    </TabsP.Root>
  );
}
export const TabPanel = TabsP.Content;

export function Switch({ checked, onChange, label }: { checked: boolean; onChange: (v: boolean) => void; label: string }) {
  return (
    <label className="inline-flex cursor-pointer items-center gap-2 text-[13px] text-fg2">
      <SwitchP.Root checked={checked} onCheckedChange={onChange} aria-label={label}
        className="relative h-5 w-9 rounded-full border border-line bg-s3 data-[state=checked]:bg-accent">
        <SwitchP.Thumb className="block h-4 w-4 translate-x-0.5 rounded-full bg-white shadow transition data-[state=checked]:translate-x-[18px]" />
      </SwitchP.Root>
      {label}
    </label>
  );
}

export function Modal({ open, onOpenChange, title, children, wide, description }: { open: boolean; onOpenChange: (o: boolean) => void;
  title: ReactNode; children: ReactNode; wide?: boolean; description?: ReactNode }) {
  return (
    <Dialog.Root open={open} onOpenChange={onOpenChange}>
      <Dialog.Portal>
        <Dialog.Overlay className="fixed inset-0 z-40 bg-black/50" />
        <Dialog.Content className={cx("fixed left-1/2 top-1/2 z-50 max-h-[88vh] -translate-x-1/2 -translate-y-1/2 overflow-auto rounded-xl border border-line bg-s1 p-5 shadow-2xl",
          wide ? "w-[min(1000px,94vw)]" : "w-[min(560px,94vw)]")}>
          <div className="mb-3 flex items-start justify-between gap-4">
            <Dialog.Title className="text-base font-semibold">{title}</Dialog.Title>
            <Dialog.Close aria-label="Close" className="text-muted hover:text-fg"><X size={16} /></Dialog.Close>
          </div>
          {description ? <Dialog.Description className="mb-3 text-xs text-fg2">{description}</Dialog.Description>
            : <Dialog.Description className="sr-only">Dialog</Dialog.Description>}
          {children}
        </Dialog.Content>
      </Dialog.Portal>
    </Dialog.Root>
  );
}

export function Field({ label, children, hint }: { label: string; children: ReactNode; hint?: ReactNode }) {
  return (
    <label className="block text-[13px]">
      <span className="mb-1 block text-xs font-medium text-fg2">{label}</span>
      {children}
      {hint && <span className="mt-1 block text-[11px] text-muted">{hint}</span>}
    </label>
  );
}

export const inputCls = "w-full rounded-lg border border-line bg-s2 px-2.5 py-1.5 text-[13px] text-fg placeholder:text-muted focus:border-accent outline-none";

export function Select({ value, onChange, options, label, testId }: { value: string; onChange: (v: string) => void;
  options: { value: string; label: string }[]; label: string; testId?: string }) {
  return (
    <select aria-label={label} value={value} data-testid={testId} onChange={(e) => onChange(e.target.value)} className={cx(inputCls, "w-auto pr-7")}>
      {options.map((o) => <option key={o.value} value={o.value}>{o.label}</option>)}
    </select>
  );
}

export function PageHeader({ title, subtitle, actions }: { title: string; subtitle?: ReactNode; actions?: ReactNode }) {
  return (
    <div className="mb-5 flex flex-wrap items-end justify-between gap-3">
      <div>
        <h1 className="text-xl font-semibold tracking-tight">{title}</h1>
        {subtitle && <p className="mt-1 max-w-3xl text-[13px] text-fg2">{subtitle}</p>}
      </div>
      {actions && <div className="flex items-center gap-2">{actions}</div>}
    </div>
  );
}

export function Grid({ children, cols = 3 }: { children: ReactNode; cols?: 2 | 3 | 4 }) {
  const c = { 2: "lg:grid-cols-2", 3: "lg:grid-cols-3", 4: "md:grid-cols-2 xl:grid-cols-4" }[cols];
  return <div className={cx("grid grid-cols-1 gap-4", c)}>{children}</div>;
}

export function Note({ children }: { children: ReactNode }) {
  return <p className="mt-2 text-[11px] leading-relaxed text-muted">{children}</p>;
}
